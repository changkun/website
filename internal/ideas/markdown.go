package ideas

import (
	"fmt"
	"regexp"
	"strings"
	"time"
	"unicode"
)

// post is one idea as the blog stores it.
type post struct {
	date      time.Time
	slug      string
	title     bilingual
	content   bilingual
	augmented bilingual
	// llmGenerated marks augmentation a model wrote, which the post discloses.
	llmGenerated bool
}

func (p post) filename() string {
	return fmt.Sprintf("%s-%s.md", p.date.Format("2006-01-02"), p.slug)
}

func (p post) path() string { return "content/ideas/" + p.filename() }

// disclaimers open generated augmentation, one per language block.
var disclaimers = bilingual{
	en: "*The following content is generated by LLMs and may contain inaccuracies.*",
	zh: "*以下内容由 LLM 生成，可能包含不准确之处。*",
}

// buildMarkdown renders p with the front matter and shortcodes the blog's
// templates read.
func buildMarkdown(p post) string {
	var b strings.Builder
	fmt.Fprintf(&b, "---\ndate: %s\nslug: %q\ntitle: %q\ntitle_zh: %q\n---\n\n",
		p.date.Format("2006-01-02T15:04:05"), p.slug, p.title.en, p.title.zh)

	var disclaimer bilingual
	if p.llmGenerated {
		disclaimer = disclaimers
	}
	writeBlock(&b, "en", p.content.en, p.augmented.en, disclaimer.en)
	b.WriteString("\n")
	writeBlock(&b, "zh", p.content.zh, p.augmented.zh, disclaimer.zh)
	return b.String()
}

// writeBlock writes one language's shortcode block: the idea, then its
// augmentation if there is one.
func writeBlock(b *strings.Builder, lang, content, augmented, disclaimer string) {
	fmt.Fprintf(b, "{{%% %s %%}}\n", lang)
	b.WriteString(content)
	if augmented != "" {
		b.WriteString("\n\n{{% augmented %}}\n")
		if disclaimer != "" {
			b.WriteString(disclaimer + "\n\n")
		}
		b.WriteString(augmented)
		b.WriteString("\n{{% /augmented %}}\n")
	}
	fmt.Fprintf(b, "{{%% /%s %%}}\n", lang)
}

var nonAlphanumRe = regexp.MustCompile(`[^a-z0-9]+`)

// slugify derives a permalink from a title mechanically, for when the model
// gives no usable slug.
func slugify(s string) string {
	s = strings.ToLower(s)
	var ascii strings.Builder
	for _, r := range s {
		if r <= unicode.MaxASCII {
			ascii.WriteRune(r)
		}
	}
	s = nonAlphanumRe.ReplaceAllString(ascii.String(), "-")
	s = strings.Trim(s, "-")
	if s == "" {
		s = "idea"
	}
	return s
}
