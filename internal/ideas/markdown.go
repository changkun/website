package ideas

import (
	"fmt"
	"regexp"
	"strings"
	"time"
	"unicode"
)

// post is an idea as the blog stores it.
type post struct {
	date         time.Time
	slug         string
	title        bilingual
	content      bilingual
	augmented    bilingual // the deep dive
	llmGenerated bool      // a model wrote the deep dive
	files        []Attachment
}

// An Attachment is a file, uploaded with Upload, that goes beside an idea.
type Attachment struct {
	Name string // in the idea's folder
	SHA  string
}

// root is where p goes in the repository: a markdown file, or, with files,
// a folder that holds it as index.md beside them.
func (p post) root() string {
	name := "content/ideas/" + p.date.Format("2006-01-02") + "-" + p.slug
	if len(p.files) == 0 {
		return name + ".md"
	}
	return name
}

// repoFiles are the files that make up p, with md its markdown.
func (p post) repoFiles(md string) []File {
	if len(p.files) == 0 {
		return []File{{Path: p.root(), Text: md}}
	}
	out := []File{{Path: p.root() + "/index.md", Text: md}}
	for _, a := range p.files {
		out = append(out, File{Path: p.root() + "/" + a.Name, SHA: a.SHA})
	}
	return out
}

// keepFiles adds a reference to each of files that text does not mention,
// as when a model drops one while it polishes or translates the text.
func keepFiles(text string, files []Attachment) string {
	for _, f := range files {
		if !strings.Contains(text, f.Name) {
			text = strings.TrimRight(text, "\n") + "\n\n![](" + f.Name + ")"
		}
	}
	return text
}

// disclaimers precede a deep dive that a model wrote.
var disclaimers = bilingual{
	en: "*The following content is generated by LLMs and may contain inaccuracies.*",
	zh: "*以下内容由 LLM 生成，可能包含不准确之处。*",
}

// buildMarkdown renders p as a Hugo page, with the front matter and shortcodes
// the blog's templates expect.
func buildMarkdown(p post) string {
	var b strings.Builder
	fmt.Fprintf(&b, "---\ndate: %s\nslug: %q\ntitle: %q\ntitle_zh: %q\n---\n\n",
		p.date.Format("2006-01-02T15:04:05"), p.slug, p.title.en, p.title.zh)

	var disclaimer bilingual
	if p.llmGenerated {
		disclaimer = disclaimers
	}
	writeBlock(&b, "en", p.content.en, p.augmented.en, disclaimer.en)
	b.WriteString("\n")
	writeBlock(&b, "zh", p.content.zh, p.augmented.zh, disclaimer.zh)
	return b.String()
}

// writeBlock writes one language's shortcode block: the idea, then its deep
// dive, if any.
func writeBlock(b *strings.Builder, lang, content, augmented, disclaimer string) {
	fmt.Fprintf(b, "{{%% %s %%}}\n", lang)
	b.WriteString(content)
	if augmented != "" {
		b.WriteString("\n\n{{% augmented %}}\n")
		if disclaimer != "" {
			b.WriteString(disclaimer + "\n\n")
		}
		b.WriteString(augmented)
		b.WriteString("\n{{% /augmented %}}\n")
	}
	fmt.Fprintf(b, "{{%% /%s %%}}\n", lang)
}

var nonAlphanumRe = regexp.MustCompile(`[^a-z0-9]+`)

// slugify derives a slug from the ASCII letters and digits of s. It is the
// fallback when the model gives no usable slug.
func slugify(s string) string {
	s = strings.ToLower(s)
	var ascii strings.Builder
	for _, r := range s {
		if r <= unicode.MaxASCII {
			ascii.WriteRune(r)
		}
	}
	s = nonAlphanumRe.ReplaceAllString(ascii.String(), "-")
	s = strings.Trim(s, "-")
	if s == "" {
		s = "idea"
	}
	return s
}
