package ideas

import (
	"testing"
	"time"
)

// TestBuildMarkdown pins the committed bytes, which the blog's templates parse.
func TestBuildMarkdown(t *testing.T) {
	date := time.Date(2026, time.November, 7, 9, 30, 0, 0, time.UTC)

	tests := []struct {
		name string
		in   post
		want string
	}{
		{
			name: "the deep dive carries the disclaimer",
			in: post{
				date:      date,
				slug:      "three-axioms",
				title:     bilingual{en: `Three "Axioms"`, zh: "三条公理"},
				content:   bilingual{en: "Body.", zh: "正文。"},
				augmented: bilingual{en: "More.", zh: "更多。"},
			},
			want: `---
date: 2026-11-07T09:30:00
slug: "three-axioms"
title: "Three \"Axioms\""
title_zh: "三条公理"
---

{{% en %}}
Body.

{{% augmented %}}
*The following content is generated by LLMs and may contain inaccuracies.*

More.
{{% /augmented %}}
{{% /en %}}

{{% zh %}}
正文。

{{% augmented %}}
*以下内容由 LLM 生成，可能包含不准确之处。*

更多。
{{% /augmented %}}
{{% /zh %}}
`,
		},
		{
			name: "one language without augmentation",
			in: post{
				date:      date,
				slug:      "s",
				title:     bilingual{en: "T", zh: "标题"},
				content:   bilingual{en: "Body.", zh: "正文。"},
				augmented: bilingual{zh: "更多。"},
			},
			want: `---
date: 2026-11-07T09:30:00
slug: "s"
title: "T"
title_zh: "标题"
---

{{% en %}}
Body.{{% /en %}}

{{% zh %}}
正文。

{{% augmented %}}
*以下内容由 LLM 生成，可能包含不准确之处。*

更多。
{{% /augmented %}}
{{% /zh %}}
`,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := buildMarkdown(tt.in); got != tt.want {
				t.Fatalf("buildMarkdown() =\n%s\nwant\n%s", got, tt.want)
			}
		})
	}
}
